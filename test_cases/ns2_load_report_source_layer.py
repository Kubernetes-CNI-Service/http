def _restore(tree, regions, previous_count, candidate_count, digest):
    """Reviewed copy of ``tree``; ``tree`` itself when it is still the reviewed one; ``None`` refuses."""
    body = getattr(tree, "body", None)
    if type(body) is not list:
        return None
    wrap = lambda node: ast.Module(body=[node], type_ignores=[])  # noqa: E731
    for kind, _label, _old_index, _new_index, old_sha, new_sha, old_src, new_src in regions:
        if (hashlib.sha256(new_src.encode()).hexdigest() != new_sha
                or (kind == "replace") != bool(old_src)
                or (old_src and hashlib.sha256(old_src.encode()).hexdigest() != old_sha)):
            raise AssertionError("generated NS2 load-report layer table is corrupt")

    def matches(index, source):
        expected = digest(wrap(ast.parse(source).body[0]))
        return (expected is not None and 0 <= index < len(body)
                and digest(wrap(body[index])) == expected)

    if len(body) == candidate_count and all(
            matches(new_index, new_src) for _k, _l, _o, new_index, _os, _ns, _old, new_src in regions):
        reviewed = copy.deepcopy(tree)
        for kind, _label, _old_index, new_index, *_rest, old_src, _new_src in reversed(regions):
            if kind == "replace":
                reviewed.body[new_index] = ast.parse(old_src).body[0]
            else:
                del reviewed.body[new_index]
        return reviewed if len(reviewed.body) == previous_count else None
    if len(body) == previous_count and all(
            matches(old_index, old_src) for kind, _l, old_index, _n, _os, _ns, old_src, _new in regions
            if kind == "replace"):
        return tree
    return None


def restore_ns2_load_report_trees(load_tree, report_tree, digest):
    """Return the reviewed pre-NS2 (load, report) modules, or ``None`` to refuse.

    ``digest`` is the caller's reviewed-AST digest (``_reviewed_source_ast_sha256``).  A module still in
    its reviewed form is returned unchanged (the unchanged pin decides); neither tree is modified.
    """
    load = _restore(load_tree, LOAD_REGIONS, LOAD_PREVIOUS_STATEMENTS, LOAD_CANDIDATE_STATEMENTS, digest)
    report = _restore(
        report_tree, REPORT_REGIONS, REPORT_PREVIOUS_STATEMENTS, REPORT_CANDIDATE_STATEMENTS, digest,
    )
    if load is None or report is None:
        return None
    return load, report
