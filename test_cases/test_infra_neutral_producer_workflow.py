#!/usr/bin/env python3
"""v3.1.2 WP-1 workflow (D-3): the real setup produces the conf the managed initial-setup consumer admits.

setup (DAY0-Prepare/01-a-setup.py) runs as a subprocess in a copy of the git-indexed workspace on a synthetic
project from examples/public-project (test_activate_project_workflow.Workspace); the fixture never writes the conf
itself.  The consumer is ztp/config_sync_authority.py::ManagedInitialMethodCycle with the real
infiniband/bringup/xdr-initial-setup/initial-setup.py as its leaf reader (_neutral_services).

Expected values, written from the sources, never from the implementation:
- 问题文档 D-3: on a project generated by the real flow, without a self-made conf, the managed path must pass.
- 参考/合并/EXECUTION-CHECKLIST.md【发布阻断项的验收要求（http merge 15:39）】: workflow -- build the root, the
  managed consumer reads it, no refusal branch fires; the known-true control -- remove the file from the tool
  root and the workflow must fail, with the failure coming from config_sync_authority.py's _neutral_image and no
  other error.  开发计划 :271 / 详细工作指导 WP-1: the message is
  "managed initial neutral service authority is unavailable".
- 详细工作指导 WP-1: not through managed_initial_main (it takes the host-wide bring-up lock and its CLI prints only the
  exception type); the monitor-side acceptance is outside M2 (§3.2 O1 ①, a known limitation).
"""

from __future__ import annotations

import os
from pathlib import Path
import tempfile
import unittest

from test_cases import test_activate_project_workflow as ACTIVATE_WORKFLOW
from test_cases.module_loader import load_script


ROOT = Path(__file__).resolve().parents[1]
AUTHORITY = load_script("infra_neutral_producer_workflow_authority", ROOT / "ztp/config_sync_authority.py")
INITIAL = load_script("infra_neutral_producer_workflow_initial",
                      ROOT / "infiniband/bringup/xdr-initial-setup/initial-setup.py")
CONF = Path("infiniband/bringup/xdr-initial-setup/infra-neutral.conf")
UNAVAILABLE = "managed initial neutral service authority is unavailable"


class NeutralProducerToManagedConsumerWorkflowTests(unittest.TestCase):
    def generated_project(self) -> Path:
        """A project the real setup prepared and activated; the fixture adds nothing to it afterwards."""
        temporary = tempfile.TemporaryDirectory(prefix="infra-neutral-producer-workflow-")
        self.addCleanup(temporary.cleanup)
        space = ACTIVATE_WORKFLOW.Workspace(Path(temporary.name).resolve())
        project = space.project(ACTIVATE_WORKFLOW.FIRST)
        self.assertFalse(os.path.lexists(project / "infiniband"), "fixture: no tool root before setup")
        result = space.setup(ACTIVATE_WORKFLOW.FIRST, "-y")
        self.assertEqual(0, result.returncode, result.stdout)
        self.assertEqual(ACTIVATE_WORKFLOW.FIRST, space.pointer())
        # The consumer's own precondition on the project root, which the fixture made (not setup): owned, not
        # group- or world-writable, whatever the umask of this run.
        os.chmod(project, 0o755)
        return project

    def test_real_setup_project_admits_neutral_image_without_fixture_conf(self):
        project = self.generated_project()
        cycle = AUTHORITY.ManagedInitialMethodCycle(project, INITIAL)
        try:
            image = cycle._neutral_image()
        except AUTHORITY.AuthorityError as exc:
            self.fail(f"D-3: the managed consumer refused the setup-made tool root: {exc}")
        self.assertEqual(os.fspath((project / CONF).resolve()), image[0])
        self.assertEqual(INITIAL._neutral_services(project / CONF.parent),
                         INITIAL._neutral_services(ROOT / "infra"), "the same services as infra/'s file")

    def test_removing_generated_conf_turns_red_at_neutral_image(self):
        project = self.generated_project()
        conf = project / CONF
        self.assertTrue(conf.is_file(), "D-3: setup generated the conf this control removes")
        conf.unlink()
        cycle = AUTHORITY.ManagedInitialMethodCycle(project, INITIAL)
        with self.assertRaises(AUTHORITY.AuthorityError) as refused:
            cycle._neutral_image()
        self.assertEqual(UNAVAILABLE, str(refused.exception))


if __name__ == "__main__":
    unittest.main()
