# Modified EUI-64 per RFC 4291 Appendix A, worked by hand, not computed by the code under test:
# invert the universal/local bit (0x02) of the first octet and insert ff:fe between octets 3 and 4.
# 02:00:00:47:57:58: first octet 0x02 -> 0x00, octets 00 00 00 ff fe 47 57 58, IID
# 0000:00ff:fe47:5758, address fe80::ff:fe47:5758.
# Only locally administered MACs may appear as literals in public source, so these vectors pin the
# 1 -> 0 direction of the U/L inversion.  The v15 vectors also pinned 0 -> 1 with globally
# administered literals, which the public audit rejects; DOCUMENTATION_EUI64_VECTORS below pins
# that direction with MACs built at run time.
EUI64_VECTORS = (
    ("02:00:00:47:57:58", "fe80::ff:fe47:5758"),
    ("02:00:00:AB:CD:EF", "fe80::ff:feab:cdef"),   # upper-case input (v15 used an upper-case vector)
    ("02:00:00:12:34:56", "fe80::ff:fe12:3456"),
    ("02:00:00:00:00:0a", "fe80::ff:fe00:a"),       # kept from v15
)


def octets(*values: int) -> str:
    """A MAC from integer octets, for protocol constants that are not device identities."""
    return ":".join("%02x" % value for value in values)


# The 0 -> 1 direction of the U/L inversion.  RFC 7042 sets aside for documentation the EUI-48
# unicast values under the IANA OUI 00-00-5E whose last three octets start with 00-53 (256
# values).  Their first octet 0x00 has the universal/local bit clear (universally administered)
# and no device is assigned one; they are built at run time by documentation_mac(), so no MAC
# literal appears in this source.  Worked by hand per RFC 4291 Appendix A, not computed by the
# code under test: first octet 0x00 -> 0x02, insert ff:fe between octets 3 and 4, octets
# 02 00 5e ff fe 00 53 <last>, IID 0200:5eff:fe00:53<last>, address fe80::200:5eff:fe00:53<last>.
# The direction comes from the v15 delivered test test_desktop_initial_setup.py::
# FdbEui64FallbackTests.test_modified_eui64_known_vectors_and_ul_bit (:1371), whose vectors at
# :1373-:1375 are universally administered (U/L bit 0 -> 1).
DOCUMENTATION_EUI64_VECTORS = (
    (0x01, "fe80::200:5eff:fe00:5301"),
    (0xAB, "fe80::200:5eff:fe00:53ab"),
    (0x00, "fe80::200:5eff:fe00:5300"),
)


def documentation_mac(last: int) -> str:
    """An RFC 7042 documentation EUI-48 unicast value (OUI 00-00-5E, then 00-53 and `last`)."""
    return octets(0x00, 0x00, 0x5E, 0x00, 0x53, last)


def target():
    ib = app.Device("example-ib001", "ib", "192.0.2.10", "192.0.2.10/24",
                    "192.0.2.1", "02:00:00:00:00:10", "", "")
    eth = app.Device("example-oob-leaf01", "eth_jump", "198.51.100.10", "", "", "", "", "")
    return app.Target(ib, eth, "swp1", "eth0")


class Eui64FallbackTests(unittest.TestCase):
    MAC = "02:00:00:47:57:58"
    IPV6 = "fe80::ff:fe47:5758"           # EUI64_VECTORS[0], derived by hand above
    OTHER_MAC = "02:00:00:47:57:20"       # a second dynamic MAC / a wrong CSV MAC
    BRIDGE_MAC = "02:00:00:b2:90:39"      # the bridge's own permanent entry
    FDB = (MAC + " dev swp6 vlan 1000 master br_default\n"
           + BRIDGE_MAC + " dev swp6 master br_default permanent\n")
    LINKS = ("6: swp6: <UP> mtu 9216 master br_default state UP\n"
             "40: br_default: <UP> mtu 9216 state UP\n"
             "    bridge forward_delay 1500 vlan_filtering 1\n"
             "41: ib-oob@br_default: <UP> mtu 9216 master oob state UP\n"
             "    vlan protocol 802.1Q id 1000 <REORDER_HDR>\n")

    def prepare(self, *, fdb=None, links=None, nd="", csv_mac=MAC, oper="up"):
        original = target()
        device = app.Target(replace(original.ib, eth0_mac=csv_mac), original.ethernet, "swp6", "eth0")
        records, outcomes, messages = {}, {}, []
        args = SimpleNamespace(eth_user="cumulus", connect_timeout=5)
        with patch.object(app, "interface_vrf", return_value="oob") as vrf, \
             patch.object(app, "interactive_run", side_effect=AssertionError("Preflight must not open IB SSH")), \
             patch.object(app, "log", lambda message="": messages.append(message)):
            ready = app.prepare_ready_ib_tasks(
                [device], args, {"example-oob-leaf01": ""}, set(),
                {"example-oob-leaf01": f"swp6 up {oper}\n"},
                {"example-oob-leaf01": (self.LINKS if links is None else links,
                                        self.FDB if fdb is None else fdb, nd)}, {}, outcomes, records)
        return ready, records, "\n".join(messages), vrf.call_count

    # v15 FdbEui64FallbackTests.test_modified_eui64_known_vectors_and_ul_bit (test_desktop_initial_setup.py:1371)
    def test_modified_eui64_known_vectors_and_ul_bit(self):
        for mac, expected in EUI64_VECTORS:
            with self.subTest(mac=mac):
                self.assertEqual(app.mac_to_link_local(mac), expected)

    # v15 FdbEui64FallbackTests.test_modified_eui64_known_vectors_and_ul_bit (test_desktop_initial_setup.py:1371),
    # its 0 -> 1 vectors (:1373-:1375) rewritten on RFC 7042 documentation values (WP-7b, wa7-9 (a)).
    # The sub-test labels carry only the last octet and the letter case, never the whole MAC.
    def test_modified_eui64_sets_ul_bit_of_universally_administered_mac(self):
        for last, expected in DOCUMENTATION_EUI64_VECTORS:
            for case in ("lower", "upper"):
                mac = getattr(documentation_mac(last), case)()
                with self.subTest(last_octet="%02x" % last, case=case):
                    self.assertEqual(app.mac_to_link_local(mac), expected)

    # v15 FdbEui64FallbackTests.test_invalid_zero_multicast_and_broadcast_macs_are_not_candidates (test_desktop_initial_setup.py:1380)
    def test_invalid_zero_multicast_and_broadcast_macs_are_not_candidates(self):
        # All-zero, IEEE group (I/G bit of the first octet set; the IPv4 multicast MAC block of
        # RFC 1112 section 6.4) and broadcast MACs are protocol constants, built at run time.
        for mac in ("invalid", octets(0, 0, 0, 0, 0, 0), octets(0x01, 0x00, 0x5E, 0x00, 0x00, 0x01),
                    octets(*([0xFF] * 6))):
            with self.subTest(mac=mac), self.assertRaises(app.SetupError):
                app.mac_to_link_local(mac)

    # v15 FdbEui64FallbackTests.test_user_evidence_becomes_candidate_using_actual_svi_and_vrf (test_desktop_initial_setup.py:1385)
