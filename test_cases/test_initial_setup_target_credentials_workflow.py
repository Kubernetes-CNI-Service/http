def bound_file(path):
    fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    try:
        first = nine(os.fstat(fd))
        if not stat.S_ISREG(first[2]) or first[5] != 1 or first[6] > 1048576:
            raise RuntimeError("FIXTURE HOLD: regular single-link bounded input required")
        if nine(path.lstat()) != first:
            raise RuntimeError("FIXTURE HOLD: named/FD input mismatch")
        chunks = []
        total = 0
        while total <= first[6]:
            part = os.read(fd, min(65536, first[6] + 1 - total))
            if not part:
                break
            chunks.append(part)
            total += len(part)
        raw = b"".join(chunks)
        if len(raw) != first[6] or os.read(fd, 1):
            raise RuntimeError("FIXTURE HOLD: changing bounded input")
        if nine(os.fstat(fd)) != first or nine(path.lstat()) != first:
            raise RuntimeError("FIXTURE HOLD: changing input identity")
        return first, raw
    finally:
        os.close(fd)

def public_key(seed, comment):
    def field(raw):
        return struct.pack(">I", len(raw)) + raw
    blob = field(b"ssh-ed25519") + field(bytes([seed]) * 32)
    return "ssh-ed25519 " + base64.b64encode(blob).decode() + " " + comment + "\n"

